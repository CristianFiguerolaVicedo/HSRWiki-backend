package com.crifigvic.hsrwiki.controller;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.Resource;
import org.springframework.http.CacheControl;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;

/**
 * The endgame modes (Memory of Chaos, Pure Fiction, Apocalyptic Shadow, Anomaly Arbitration):
 * current and upcoming phases with their effects, buffs and enemies (data/endgame_data.json,
 * generated by data-pipeline/update_endgame.py) plus the recommended teams written by hand
 * (data/endgame_teams.json). Served together as {"data": ..., "teams": ...}.
 */
@Slf4j
@RestController
@RequestMapping("/api/endgame")
public class EndgameController {

    private final String json;

    public EndgameController(@Value("${hsrwiki.endgame-file:classpath:data/endgame_data.json}") Resource data,
                             @Value("${hsrwiki.endgame-teams-file:classpath:data/endgame_teams.json}") Resource teams) {
        this.json = "{\"data\":" + read(data, "{\"modes\":[]}") + ",\"teams\":" + read(teams, "{\"phases\":{}}") + "}";
    }

    private static String read(Resource file, String fallback) {
        try (InputStream in = file.getInputStream()) {
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            log.warn("No endgame file found ({}): the Endgame page will be empty", e.getMessage());
            return fallback;
        }
    }

    @GetMapping
    public ResponseEntity<String> getEndgame() {
        return ResponseEntity.ok()
                .contentType(MediaType.APPLICATION_JSON)
                .cacheControl(CacheControl.noCache())
                .body(json);
    }
}
