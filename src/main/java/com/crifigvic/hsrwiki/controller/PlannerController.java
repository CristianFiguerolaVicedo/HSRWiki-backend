package com.crifigvic.hsrwiki.controller;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.Resource;
import org.springframework.http.CacheControl;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.TimeUnit;

/**
 * Material planner data (ascension, trace and EXP costs), generated by
 * data-pipeline/update_planner_data.py. It is served as-is: the planner does the maths in the browser.
 */
@Slf4j
@RestController
@RequestMapping("/api/planner")
public class PlannerController {

    private final String plannerJson;

    public PlannerController(@Value("${hsrwiki.planner-file:classpath:data/planner_data.json}") Resource file) {
        String json;
        try (InputStream in = file.getInputStream()) {
            json = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            log.error("Planner data not found; run data-pipeline/update_planner_data.py", e);
            json = null;
        }
        this.plannerJson = json;
    }

    @GetMapping
    public ResponseEntity<String> getPlannerData() {
        if (plannerJson == null) {
            return ResponseEntity.status(503).contentType(MediaType.APPLICATION_JSON)
                    .body("{\"error\":\"Planner data isn't available on this server.\"}");
        }
        return ResponseEntity.ok()
                .contentType(MediaType.APPLICATION_JSON)
                .cacheControl(CacheControl.maxAge(1, TimeUnit.HOURS))
                .body(plannerJson);
    }
}
