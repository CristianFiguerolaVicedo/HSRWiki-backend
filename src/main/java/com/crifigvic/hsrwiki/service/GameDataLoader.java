package com.crifigvic.hsrwiki.service;

import com.crifigvic.hsrwiki.entity.*;
import com.crifigvic.hsrwiki.entity.Character;
import com.crifigvic.hsrwiki.util.Element;
import com.crifigvic.hsrwiki.util.Path;
import jakarta.annotation.PostConstruct;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.DefaultResourceLoader;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.io.InputStream;
import java.util.*;
import java.util.function.Function;

/**
 * Loads the game data generated by data-pipeline/update_data.py.
 * The file lives in src/main/resources/data/game_data.json by default; set
 * hsrwiki.data-file (e.g. file:/path/game_data.json) to load another one.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class GameDataLoader {

    private final ObjectMapper mapper = new ObjectMapper();
    private final Map<Integer, Character> characters = new LinkedHashMap<>();
    private final Map<Integer, Lightcone> lightcones = new LinkedHashMap<>();
    private final Map<String, RelicSet> relicSets = new LinkedHashMap<>();
    private final Map<String, Item> items = new LinkedHashMap<>();
    private final CharacterBuildService characterBuildService;

    @Value("${hsrwiki.data-file:classpath:data/game_data.json}")
    private String dataFile;

    private String gameVersion;

    @PostConstruct
    public void load() throws IOException {
        Resource resource = new DefaultResourceLoader().getResource(dataFile);
        if (!resource.exists()) {
            throw new IllegalStateException("Game data not found at " + dataFile
                    + ". Run `python data-pipeline/update_data.py` to generate it.");
        }

        JsonNode root;
        try (InputStream in = resource.getInputStream()) {
            root = mapper.readTree(in);
        }

        gameVersion = getText(root, "version");
        loadCharacters(root.get("characters"));
        loadLightcones(root.get("light_cones"));
        loadRelicSets(root.get("relic_sets"));
        loadItems(root.get("items"));

        log.info("Loaded game data {}: {} characters, {} light cones, {} relic sets, {} items",
                gameVersion, characters.size(), lightcones.size(), relicSets.size(), items.size());
    }

    // ---------------------------------------------------------------- characters

    private void loadCharacters(JsonNode charsNode) {
        if (charsNode == null) return;

        for (String name : charsNode.propertyNames()) {
            JsonNode node = charsNode.get(name);
            try {
                Element element = parseElement(getText(node, "element"));
                Path path = parsePath(getText(node, "path"));
                if (!node.has("rarity") || element == null || path == null) {
                    log.warn("Skipping character {}: unknown element/path", name);
                    continue;
                }

                JsonNode enhancedNode = node.get("enhanced");
                EnhancedKit enhanced = enhancedNode == null ? null : EnhancedKit.builder()
                        .skills(parseSkills(enhancedNode.get("skills")))
                        .traces(parseTraces(enhancedNode.get("traces")))
                        .build();

                Character character = Character.builder()
                        // The game's own id is stable across data updates (name.hashCode() could collide)
                        .id(node.has("id") ? node.get("id").asInt() : name.hashCode())
                        .name(name)
                        .rarity(node.get("rarity").asInt())
                        .element(element)
                        .path(path)
                        .icon(getText(node, "icon"))
                        .splash(getText(node, "splash"))
                        .miniIcon(getText(node, "mini_icon"))
                        .ascension(parseAscensions(node.get("ascension")))
                        .eidolons(parseEidolons(node.get("eidolons")))
                        .skills(parseSkills(node.get("skills")))
                        .traces(parseTraces(node.get("traces")))
                        .enhanced(enhanced)
                        .build(characterBuildService.getBuildForCharacter(name))
                        .build();

                characters.put(character.getId(), character);
            } catch (RuntimeException e) {
                // One malformed entry shouldn't take the whole API down
                log.error("Error parsing character {}", name, e);
            }
        }
    }

    static Path parsePath(String raw) {
        if (raw == null) return null;
        try {
            return Path.valueOf(raw.replace("The ", "").trim().toUpperCase());
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    static Element parseElement(String raw) {
        if (raw == null) return null;
        String value = raw.trim().toUpperCase();
        if (value.equals("THUNDER")) value = "LIGHTNING";
        try {
            return Element.valueOf(value);
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    private List<Ascension> parseAscensions(JsonNode ascensionsNode) {
        List<Ascension> ascensions = new ArrayList<>();
        if (ascensionsNode == null || !ascensionsNode.isArray()) return ascensions;

        for (JsonNode ascNode : ascensionsNode) {
            ascensions.add(Ascension.builder()
                    .hp(parseStatValue(ascNode.get("hp")))
                    .atk(parseStatValue(ascNode.get("atk")))
                    .def(parseStatValue(ascNode.get("def")))
                    .spd(parseStatValue(ascNode.get("spd")))
                    .taunt(parseStatValue(ascNode.get("taunt")))
                    .critRate(parseStatValue(ascNode.get("crit_rate")))
                    .critDmg(parseStatValue(ascNode.get("crit_dmg")))
                    .build());
        }
        return ascensions;
    }

    private StatValue parseStatValue(JsonNode statNode) {
        if (statNode == null) return null;
        return StatValue.builder()
                .base(statNode.path("base").asDouble())
                .step(statNode.path("step").asDouble())
                .build();
    }

    private List<Eidolon> parseEidolons(JsonNode eidolonsNode) {
        List<Eidolon> eidolons = new ArrayList<>();
        if (eidolonsNode == null || !eidolonsNode.isArray()) return eidolons;

        for (JsonNode eidolonNode : eidolonsNode) {
            Eidolon eidolon = Eidolon.builder()
                    .name(getText(eidolonNode, "name"))
                    .desc(getText(eidolonNode, "desc"))
                    .build();

            JsonNode levelUpSkillsNode = eidolonNode.get("level_up_skills");
            if (levelUpSkillsNode != null) {
                Map<String, Integer> levelUpSkills = new LinkedHashMap<>();
                for (String key : levelUpSkillsNode.propertyNames()) {
                    levelUpSkills.put(key, levelUpSkillsNode.get(key).asInt());
                }
                eidolon.setLevelUpSkills(levelUpSkills);
            }
            eidolons.add(eidolon);
        }
        return eidolons;
    }

    private Skill parseSkills(JsonNode skillsNode) {
        if (skillsNode == null) return null;

        List<ExtraSkill> extra = new ArrayList<>();
        JsonNode extraNode = skillsNode.get("extra");
        if (extraNode != null && extraNode.isArray()) {
            for (JsonNode n : extraNode) {
                extra.add(ExtraSkill.builder()
                        .name(getText(n, "name"))
                        .type(getText(n, "type"))
                        .maxLevel(n.path("max_level").asInt())
                        .desc(getText(n, "desc"))
                        .params(parseParams(n.get("params")))
                        .build());
            }
        }

        return Skill.builder()
                .basic(parseSkill(skillsNode.get("basic"), n -> BasicSkill.builder()
                        .name(getText(n, "name")).maxLevel(n.path("max_level").asInt())
                        .desc(getText(n, "desc")).params(parseParams(n.get("params"))).build()))
                .skill(parseSkill(skillsNode.get("skill"), n -> ActiveSkill.builder()
                        .name(getText(n, "name")).maxLevel(n.path("max_level").asInt())
                        .desc(getText(n, "desc")).params(parseParams(n.get("params"))).build()))
                .ult(parseSkill(skillsNode.get("ult"), n -> UltimateSkill.builder()
                        .name(getText(n, "name")).maxLevel(n.path("max_level").asInt())
                        .desc(getText(n, "desc")).params(parseParams(n.get("params"))).build()))
                .talent(parseSkill(skillsNode.get("talent"), n -> TalentSkill.builder()
                        .name(getText(n, "name")).maxLevel(n.path("max_level").asInt())
                        .desc(getText(n, "desc")).params(parseParams(n.get("params"))).build()))
                .extra(extra.isEmpty() ? null : extra)
                .build();
    }

    private <T> T parseSkill(JsonNode node, Function<JsonNode, T> builder) {
        return node == null ? null : builder.apply(node);
    }

    private List<List<String>> parseParams(JsonNode paramsNode) {
        List<List<String>> params = new ArrayList<>();
        if (paramsNode == null || !paramsNode.isArray()) return params;

        for (JsonNode paramArray : paramsNode) {
            List<String> paramList = new ArrayList<>();
            if (paramArray.isArray()) {
                for (JsonNode param : paramArray) {
                    paramList.add(param.asString());
                }
            }
            params.add(paramList);
        }
        return params;
    }

    private Trace parseTraces(JsonNode tracesNode) {
        if (tracesNode == null) return null;

        JsonNode technique = tracesNode.get("technique");
        Map<String, AbilityTrace> abilities = new LinkedHashMap<>();
        Map<String, StatTrace> stats = new LinkedHashMap<>();

        for (int i = 1; i <= 3; i++) {
            JsonNode n = tracesNode.get("ability_" + i);
            if (n != null) {
                abilities.put("ability_" + i, AbilityTrace.builder()
                        .name(getText(n, "name")).desc(getText(n, "desc")).build());
            }
        }
        for (int i = 1; i <= 10; i++) {
            JsonNode n = tracesNode.get("stat_" + i);
            if (n != null) {
                stats.put("stat_" + i, StatTrace.builder()
                        .name(getText(n, "name"))
                        .desc(getText(n, "desc"))
                        .modifiers(parseModifiers(n.get("modifiers")))
                        .build());
            }
        }

        List<AbilityTrace> extra = new ArrayList<>();
        JsonNode extraNode = tracesNode.get("extra");
        if (extraNode != null && extraNode.isArray()) {
            for (JsonNode n : extraNode) {
                extra.add(AbilityTrace.builder().name(getText(n, "name")).desc(getText(n, "desc")).build());
            }
        }

        return Trace.builder()
                .technique(technique == null ? null : TechniqueTrace.builder()
                        .name(getText(technique, "name")).desc(getText(technique, "desc")).build())
                .abilities(abilities)
                .stats(stats)
                .extra(extra.isEmpty() ? null : extra)
                .build();
    }

    private List<Modifier> parseModifiers(JsonNode modifiersNode) {
        List<Modifier> modifiers = new ArrayList<>();
        if (modifiersNode == null || !modifiersNode.isArray()) return modifiers;

        for (JsonNode modifierNode : modifiersNode) {
            modifiers.add(Modifier.builder()
                    .type(getText(modifierNode, "type"))
                    .value(modifierNode.path("value").asDouble())
                    .build());
        }
        return modifiers;
    }

    // ---------------------------------------------------------------- light cones

    private void loadLightcones(JsonNode lightconesNode) {
        if (lightconesNode == null) return;

        for (String name : lightconesNode.propertyNames()) {
            JsonNode node = lightconesNode.get(name);
            Path path = parsePath(getText(node, "path"));
            if (!node.has("rarity") || path == null) continue;

            Lightcone lightcone = Lightcone.builder()
                    .id(name.hashCode())
                    .name(name)
                    .rarity(node.get("rarity").asInt())
                    .path(path)
                    .desc(getText(node, "desc"))
                    .icon(getText(node, "icon"))
                    .image(getText(node, "image"))
                    .miniIcon(getText(node, "mini_icon"))
                    .ascensions(parseLightconeAscensions(node.get("ascension")))
                    .ability(parseLightconeAbility(node.get("ability")))
                    .build();

            lightcones.put(lightcone.getId(), lightcone);
        }
    }

    private List<LightconeAscension> parseLightconeAscensions(JsonNode ascensionsNode) {
        List<LightconeAscension> ascensions = new ArrayList<>();
        if (ascensionsNode == null || !ascensionsNode.isArray()) return ascensions;

        for (JsonNode ascNode : ascensionsNode) {
            ascensions.add(LightconeAscension.builder()
                    .hp(parseStatValue(ascNode.get("hp")))
                    .atk(parseStatValue(ascNode.get("atk")))
                    .def(parseStatValue(ascNode.get("def")))
                    .build());
        }
        return ascensions;
    }

    private LightconeAbility parseLightconeAbility(JsonNode abilityNode) {
        if (abilityNode == null) return null;
        return LightconeAbility.builder()
                .name(getText(abilityNode, "name"))
                .desc(getText(abilityNode, "desc"))
                .params(parseParams(abilityNode.get("params")))
                .build();
    }

    // ---------------------------------------------------------------- relics

    private void loadRelicSets(JsonNode relicNode) {
        if (relicNode == null) return;

        for (String name : relicNode.propertyNames()) {
            JsonNode node = relicNode.get(name);
            try {
                relicSets.put(name, RelicSet.builder()
                        .name(name)
                        .pieces(parsePieces(node.get("pieces")))
                        .desc(parseStringArray(node.get("desc")))
                        .modifiers(parseSetModifiers(node.get("modifiers")))
                        .build());
            } catch (RuntimeException e) {
                log.error("Error parsing relic set {}", name, e);
            }
        }
    }

    private Map<String, Piece> parsePieces(JsonNode piecesNode) {
        Map<String, Piece> pieces = new LinkedHashMap<>();
        if (piecesNode == null || !piecesNode.isObject()) return pieces;

        for (String pieceType : piecesNode.propertyNames()) {
            JsonNode pieceNode = piecesNode.get(pieceType);
            pieces.put(pieceType, Piece.builder()
                    .name(getText(pieceNode, "name"))
                    .icon(getText(pieceNode, "icon"))
                    .build());
        }
        return pieces;
    }

    private List<List<Modifier>> parseSetModifiers(JsonNode modifiersNode) {
        List<List<Modifier>> allModifiers = new ArrayList<>();
        if (modifiersNode == null || !modifiersNode.isArray()) return allModifiers;

        for (JsonNode modifierArray : modifiersNode) {
            allModifiers.add(parseModifiers(modifierArray));
        }
        return allModifiers;
    }

    // ---------------------------------------------------------------- items

    private void loadItems(JsonNode itemsNode) {
        if (itemsNode == null) return;

        for (String name : itemsNode.propertyNames()) {
            JsonNode node = itemsNode.get(name);
            items.put(name, Item.builder()
                    .id(getText(node, "id"))
                    .name(name)
                    .rarity(node.has("rarity") ? node.get("rarity").asInt() : 1)
                    .type(getText(node, "type"))
                    .sub_type(getText(node, "sub_type"))
                    .icon(getText(node, "icon"))
                    .come_from(parseStringArray(node.get("come_from")))
                    .category(getText(node, "category"))
                    .desc(getText(node, "desc"))
                    .lore(getText(node, "lore"))
                    .usedBy(parseItemUsage(node.get("used_by")))
                    .build());
        }
    }

    /** Turns the names in "used_by" into links; runs after characters and light cones are loaded. */
    private ItemUsage parseItemUsage(JsonNode usedByNode) {
        if (usedByNode == null) return null;

        Map<String, Character> charactersByName = new HashMap<>();
        characters.values().forEach(c -> charactersByName.put(c.getName(), c));

        List<ItemUsage.Ref> chars = new ArrayList<>();
        for (String name : parseStringArray(usedByNode.get("characters"))) {
            Character c = charactersByName.get(name);
            if (c != null) {
                chars.add(ItemUsage.Ref.builder().id(c.getId()).name(name).icon(c.getMiniIcon()).build());
            }
        }
        List<ItemUsage.Ref> cones = new ArrayList<>();
        for (String name : parseStringArray(usedByNode.get("light_cones"))) {
            Lightcone lc = getLightconeByName(name);
            if (lc != null) {
                cones.add(ItemUsage.Ref.builder().id(lc.getId()).name(name).icon(lc.getMiniIcon()).build());
            }
        }
        return ItemUsage.builder()
                .characters(chars)
                .lightCones(cones)
                .everyone(usedByNode.path("everyone").asBoolean(false))
                .build();
    }

    // ---------------------------------------------------------------- helpers

    private String getText(JsonNode node, String field) {
        JsonNode value = node == null ? null : node.get(field);
        return value == null || value.isNull() ? null : value.asString();
    }

    private List<String> parseStringArray(JsonNode arrayNode) {
        List<String> list = new ArrayList<>();
        if (arrayNode != null && arrayNode.isArray()) {
            for (JsonNode item : arrayNode) {
                if (item.isString()) list.add(item.asString());
            }
        }
        return list;
    }

    // ---------------------------------------------------------------- queries (null when not found)

    public String getGameVersion() {
        return gameVersion;
    }

    public Collection<Character> getAllCharacters() {
        return characters.values();
    }

    public Character getById(int id) {
        return characters.get(id);
    }

    public Collection<Lightcone> getAllLightcones() {
        return lightcones.values();
    }

    public Lightcone getLightconeById(int id) {
        return lightcones.get(id);
    }

    public Lightcone getLightconeByName(String name) {
        return lightcones.get(name.hashCode());
    }

    public Collection<RelicSet> getAllRelicSets() {
        return relicSets.values();
    }

    public RelicSet getRelicSetByName(String name) {
        return relicSets.get(name);
    }

    public Collection<Item> getAllItems() {
        return items.values();
    }

    public Item getItemById(String id) {
        return items.values().stream()
                .filter(item -> id.equals(item.getId()))
                .findFirst()
                .orElse(null);
    }

    public Item getItemByName(String name) {
        return items.get(name);
    }
}
